"""Descriptive tables for the outcome and nine candidates; Plotter owns rendering."""
from pathlib import Path
import numpy as np
import pandas as pd
from .variables import CANDIDATES
from .data_loader import OUTCOME, PERCENT_COLUMNS
from .plotter import Plotter


class MigrationDescriptives:
    def __init__(self, data_loader, output_dir, geojson_path=None, plotter=None):
        self.loader = data_loader
        self.output_dir = Path(output_dir).expanduser().resolve()
        self.tables_dir = self.output_dir / 'tables'
        self.tables_dir.mkdir(parents=True, exist_ok=True)
        self.plotter = plotter or Plotter(self.output_dir / 'figures')
        self.geojson_path = Path(geojson_path).resolve() if geojson_path else None
        self.paired = self.loader.get_paired_outcomes()
        self.outputs = []

    @staticmethod
    def _stats(series):
        values = series.to_numpy(dtype=float)
        finite = pd.Series(values[np.isfinite(values)])
        return dict(n_total=len(values), n_valid=len(finite),
                    n_missing_or_nonfinite=int((~np.isfinite(values)).sum()),
                    mean=finite.mean(), median=finite.median(), sd=finite.std(ddof=1),
                    min=finite.min(), q25=finite.quantile(.25),
                    q75=finite.quantile(.75), max=finite.max())

    def _table(self, name, frame):
        path = self.tables_dir / f'{name}.csv'
        frame.to_csv(path, index=False, float_format='%.10g')
        self.outputs.append(path)

    def export_tables(self):
        raw = self.loader.get_long_data()
        sources = [c[0] for c in CANDIDATES]
        missing = [c for c in sources if c not in raw]
        if missing: raise ValueError(f'Missing selected descriptive variables: {missing}')
        rows = []
        for sex in ['female', 'male']:
            df = raw.loc[raw.sex.eq(sex)]
            for source, key, method, domain in CANDIDATES:
                unit = ('percent_0_to_100' if source in PERCENT_COLUMNS else
                        'people_per_household' if key=='household_size' else
                        'source_units_verify_documentation')
                rows.append(dict(sex=sex, variable=source, feature=key, domain=domain,
                                 scale=unit, **self._stats(df[source])))
        self._table('selected_variable_descriptives', pd.DataFrame(rows))
        self._table('county_sex_selected_data', raw[['County','county_key','sex',OUTCOME]+sources])
        self._table('county_migration_and_gap', self.paired)
        self._table('outcome_summary', pd.DataFrame([
            dict(measure=label, unit=unit, **self._stats(self.paired[col]))
            for label, col, unit in [('female_prevalence','female_pct','percent'),
                                    ('male_prevalence','male_pct','percent'),
                                    ('female_minus_male_gap','gap_pp','percentage_points')]]))
        self._table('gap_direction_counts', pd.DataFrame([
            dict(higher_recorded_prevalence=label,
                 n_counties=int(self.paired.higher_recorded_prevalence.eq(label).sum()))
            for label in ['female','male','equal']]))
        # Full-source audit remains available even though descriptive summaries use nine candidates.
        self._table('data_quality_flags', pd.DataFrame(self.loader.issues,
                    columns=['sex','county','variable','value','issue']))
        self._table('composition_checks', pd.DataFrame(self.loader.composition_checks))
        self._table('source_manifest', pd.DataFrame(self.loader.source_manifest))

    def run(self, make_maps=True):
        self.export_tables()
        self.plotter.candidate_distributions(self.loader.get_long_data())
        if make_maps:
            join = self.plotter.plot_maps(self.paired, self.geojson_path)
            self._table('map_county_join', join)
        notes = (
            'Unweighted county summaries, not national prevalence estimates.\n'
            'Outcome: reported born in Kenya but outside current place of residence.\n'
            'Gender gaps are descriptive, with no survey-based significance tests.\n'
            'Nine candidate summaries use original source units; SD is across counties, not a survey SE.\n'
            'Only the density distribution chart has a logarithmic axis.\n'
            'Completed_secondary is one source category, not secondary-or-higher; education flags remain.\n'
            'Gini remains on its supplied scale; verify units, years and all source definitions.\n'
            'Source data are not imputed, normalized or corrected. Full-source composition flags are retained.\n'
            'All figures are generated by Plotter. Two prevalence maps use a fixed shared 0–100% scale.\n'
            'Maps require matching WGS84 county GeoJSON, shapely and pyproj.\n')
        path = self.output_dir/'analysis_notes.txt'; path.write_text(notes)
        self.outputs.append(path)
        return self.outputs + self.plotter.outputs
